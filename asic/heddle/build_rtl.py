"""Turn the trained model file into the tile's hardwired weight logic.

Writes `heddle_model.vh` (dimensions) and `heddle_model.v` (weight columns,
token embedding, sampler table and the bit counter). Every weight becomes a
constant in a case statement. Synthesis reduces those constants to gates, so
the fabricated tile carries the model in its logic and has no weight memory.
"""
import argparse
from pathlib import Path

from heddle import MODEL, Model


def shape(model):
    """Datapath dimensions shared by the generator and the testbenches."""
    hidden = max(len(rows) for _, rows in model.layers[:-1])
    width = max(model.context * model.embed_bits, hidden)
    low = high = 0
    for inputs, rows in model.layers:
        for pos, neg, c in rows:
            low = min(low, c)
            high = max(high, c + 2 * bin(pos | neg).count("1"))
    high += max(model.gumbel)
    value_bits = max(low.bit_length(), high.bit_length()) + 1
    constants = [c for _, rows in model.layers for _, _, c in rows]
    return {
        "W": width,
        "HW": hidden,
        "D0": model.context * model.embed_bits,
        "E": model.embed_bits,
        "K": model.context,
        "R": model.rows,
        "RB": max(1, (model.rows - 1).bit_length()),
        "PB": width.bit_length(),
        "CB": max(abs(min(constants)).bit_length(), max(constants).bit_length()) + 1,
        "VB": value_bits,
        "GB": max(1, max(model.gumbel).bit_length()),
    }


def placed_rows(model):
    """Yield (pos, neg, c, layer_end, is_out) with columns in datapath order.

    Layer 0 reads the context in columns 0 upward. Each later layer reads the
    shift register that collected the previous layer, whose last row sits in
    that register's top bit, so its weights are placed against that end.
    """
    width = max(len(rows) for _, rows in model.layers[:-1])
    for number, (inputs, rows) in enumerate(model.layers):
        shift = 0 if number == 0 else width - inputs
        for index, (pos, neg, c) in enumerate(rows):
            yield pos << shift, neg << shift, c, index == len(rows) - 1, number == len(model.layers) - 1


def popcount(width, out_bits):
    """Carry-save reduction to two words, then one carry-propagate adder."""
    lines = [f"module heddle_popcount (input wire [{width - 1}:0] bits, output wire [{out_bits - 1}:0] count);"]
    columns = {0: [f"bits[{i}]" for i in range(width)]}
    serial = 0
    while max(len(column) for column in columns.values()) > 2:
        reduced = {}
        for weight in sorted(columns):
            column = columns[weight]
            keep = reduced.setdefault(weight, [])
            while len(column) >= 3:
                a, b, c = column.pop(), column.pop(), column.pop()
                lines.append(f"    wire s{serial} = {a} ^ {b} ^ {c};")
                lines.append(f"    wire c{serial} = ({a} & {b}) | ({a} & {c}) | ({b} & {c});")
                keep.append(f"s{serial}")
                reduced.setdefault(weight + 1, []).append(f"c{serial}")
                serial += 1
            keep.extend(column)
        columns = reduced
    top = max(columns)
    for name, pick in (("a", 0), ("b", 1)):
        word = [columns.get(w, [])[pick] if len(columns.get(w, [])) > pick else "1'b0" for w in range(top + 1)]
        lines.append(f"    wire [{top}:0] {name} = {{{', '.join(reversed(word))}}};")
    lines.append(f"    wire [{top + 1}:0] sum = a + b;")
    lines.append(f"    assign count = sum[{out_bits - 1}:0];")
    lines.append("endmodule")
    return "\n".join(lines)


def build(model, output):
    dims = shape(model)
    width, row_bits, c_bits = dims["W"], dims["RB"], dims["CB"]
    header = [f"`define HEDDLE_{name} {value}" for name, value in dims.items()]
    header.append(f"`define HEDDLE_SEED 31'h{model.seed:08x}")
    (output / "heddle_model.vh").write_text("\n".join(header) + "\n")

    # Each datapath column owns the two functions that say whether its weight is +1
    # or -1 in the current row. Keeping a column's logic in its own module stops
    # synthesis from sharing decode terms between columns. Shared terms were about
    # 30% smaller but turned every row into a net spanning the whole tile, which
    # the router could not complete. Local cones need only the row counter.
    rows = list(placed_rows(model))
    text = [f"// Generated by build_rtl.py from model {model.sha256}. Do not edit."]
    for column in range(width):
        text.append(
            f"(* keep_hierarchy *) module heddle_col{column} "
            f"(input wire [{row_bits - 1}:0] row, output reg pos, output reg neg);"
        )
        text.append("    always @* case (row)")
        for index, (pos, neg, _, _, _) in enumerate(rows):
            if (pos | neg) >> column & 1:
                text.append(
                    f"        {row_bits}'d{index}: begin pos = 1'b{pos >> column & 1}; "
                    f"neg = 1'b{neg >> column & 1}; end"
                )
        text.append("        default: begin pos = 1'b0; neg = 1'b0; end")
        text.append("    endcase")
        text.append("endmodule")
    text.append(
        f"(* keep_hierarchy *) module heddle_bias (input wire [{row_bits - 1}:0] row, "
        f"output reg signed [{c_bits - 1}:0] c, output reg layer_end, output reg is_out);"
    )
    text.append("    always @* case (row)")
    for index, (_, _, c, layer_end, is_out) in enumerate(rows):
        constant = f"-{c_bits}'sd{-c}" if c < 0 else f"{c_bits}'sd{c}"
        text.append(
            f"        {row_bits}'d{index}: begin c = {constant}; "
            f"layer_end = 1'b{int(layer_end)}; is_out = 1'b{int(is_out)}; end"
        )
    text.append(f"        default: begin c = {c_bits}'sd0; layer_end = 1'b1; is_out = 1'b1; end")
    text.append("    endcase")
    text.append("endmodule")
    text.append(
        f"module heddle_rom (input wire [{row_bits - 1}:0] row, output wire [{width - 1}:0] pos, "
        f"output wire [{width - 1}:0] neg, output wire signed [{c_bits - 1}:0] c, "
        "output wire layer_end, output wire is_out);"
    )
    for column in range(width):
        text.append(f"    heddle_col{column} col{column} (.row(row), .pos(pos[{column}]), .neg(neg[{column}]));")
    text.append("    heddle_bias bias (.row(row), .c(c), .layer_end(layer_end), .is_out(is_out));")
    text.append("endmodule")

    text.append(f"module heddle_emb (input wire [4:0] token, output reg [{dims['E'] - 1}:0] bits);")
    text.append("    always @* case (token)")
    for token, word in enumerate(model.embedding):
        text.append(f"        5'd{token}: bits = {dims['E']}'h{word:x};")
    text.append("    endcase")
    text.append("endmodule")

    text.append(f"module heddle_gumbel (input wire [4:0] index, output reg [{dims['GB'] - 1}:0] value);")
    text.append("    always @* case (index)")
    for index, value in enumerate(model.gumbel):
        text.append(f"        5'd{index}: value = {dims['GB']}'d{value};")
    text.append("    endcase")
    text.append("endmodule")
    text.append(popcount(width, dims["PB"]))
    (output / "heddle_model.v").write_text("\n".join(text) + "\n")
    return dims


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    parser.add_argument("--model", type=Path, default=MODEL)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    print(build(Model.load(args.model), args.output))
